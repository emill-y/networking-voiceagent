export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  size = 18,
  color,
  strokeWidth = 1.9,
}: {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
}) {
  const { colors } = useTheme();
  const Glyph = ICONS[name];
  return <Glyph size={size} color={color ?? colors.text} strokeWidth={strokeWidth} />;
}
